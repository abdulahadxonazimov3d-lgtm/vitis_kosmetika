function t(key) {
  return translations[currentLang]?.[key] ?? translations.uz[key] ?? key;
}

function applyLanguage(lang) {
  if (!translations[lang]) return;
  currentLang = lang;
  localStorage.setItem("vitisCosmeticsLanguage", lang);
  document.documentElement.lang = lang;
  currentLanguage.textContent = languageNames[lang];

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.dataset.i18n;
    el.textContent = translations[lang][key] ?? translations.uz[key] ?? el.textContent;
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    const key = el.dataset.i18nPlaceholder;
    el.placeholder = translations[lang][key] ?? translations.uz[key] ?? el.placeholder;
  });
  document.querySelectorAll("[data-i18n-alt]").forEach((el) => {
    const key = el.dataset.i18nAlt;
    el.alt = translations[lang][key] ?? translations.uz[key] ?? el.alt;
  });
  document.querySelectorAll("[data-i18n-aria]").forEach((el) => {
    const key = el.dataset.i18nAria;
    el.setAttribute("aria-label", translations[lang][key] ?? translations.uz[key] ?? "");
  });
  document.querySelectorAll("[data-i18n-content]").forEach((el) => {
    const key = el.dataset.i18nContent;
    el.setAttribute("content", translations[lang][key] ?? translations.uz[key] ?? "");
  });

  document.querySelectorAll(".language-menu [data-lang]").forEach((button) => {
    const selected = button.dataset.lang === lang;
    button.classList.toggle("active", selected);
    button.setAttribute("aria-selected", String(selected));
  });

  closeLanguageMenu();
  statusBox.textContent = "";
  statusBox.className = "form-status";
}

function openLanguageMenu() {
  languageSwitcher.classList.add("open");
  languageBtn.setAttribute("aria-expanded", "true");
}

function closeLanguageMenu() {
  languageSwitcher.classList.remove("open");
  languageBtn.setAttribute("aria-expanded", "false");
}

languageBtn?.addEventListener("click", (event) => {
  event.stopPropagation();
  languageSwitcher.classList.contains("open") ? closeLanguageMenu() : openLanguageMenu();
});

languageMenu?.querySelectorAll("[data-lang]").forEach((button) => {
  button.addEventListener("click", () => applyLanguage(button.dataset.lang));
});

document.addEventListener("click", (event) => {
  if (!languageSwitcher?.contains(event.target)) closeLanguageMenu();
});

document.addEventListener("keydown", (event) => {
  if (event.key === "Escape") closeLanguageMenu();
});

